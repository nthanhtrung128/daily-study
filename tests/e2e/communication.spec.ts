import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import { audit } from './helpers/audit';
import { stubMedia, watchCsp } from './helpers/stubs';

test('giao tiếp từ Hôm nay tới ghi âm, nhắc lịch và đánh giá theo ngày', async ({ page }) => {
  test.slow();
  await page.addInitScript(stubMedia);
  await page.addInitScript(watchCsp);
  await page.clock.setFixedTime(new Date('2026-11-23T12:00:00+07:00'));
  await page.goto('./#hom-nay');
  await page.getByRole('link', { name: 'Luyện · Bắt chuyện trước cuộc họp' }).click();
  await page.getByRole('button', { name: 'Welcome! How has your visit been so far?' }).click();
  const issues: string[] = [];
  await audit(page, 'Đối chiếu lời đáp và tự đánh giá', issues);
  expect(issues).toEqual([]);
  await page.getByRole('button', { name: 'Ghi và nghe lại câu trả lời' }).click();
  await page.getByRole('button', { name: 'Bắt đầu ghi âm' }).click();
  await page.getByRole('button', { name: 'Dừng & lưu' }).click();
  await expect(page.getByTestId('rec-status')).toContainText('Đã lưu');
  await page.getByRole('checkbox').first().check();
  await page.getByRole('button', { name: 'Hoàn thành lượt luyện' }).click();
  await expect(page.getByRole('heading', { name: 'Kết quả buổi luyện' })).toBeVisible();
  await page.getByText('Nhắc ôn định kỳ bài này', { exact: true }).click();
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Tạo lời nhắc cho bài' }).click()]);
  const text = (await readFile((await download.path())!, 'utf8')).replace(/\r\n /g, '');
  expect(text).toContain('UID:cc-01@daily-study.app');
  expect(text).toContain('BEGIN:VALARM');
  await page.getByRole('link', { name: 'Xem tiến độ kỹ năng' }).click();
  await expect(page.getByRole('region', { name: 'Giao tiếp công sở' })).toContainText('1/6 buổi đã luyện');
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00+07:00'));
  await page.reload();
  await page.getByRole('link', { name: 'Ôn lại · Bắt chuyện trước cuộc họp' }).click();
  await page.getByRole('button', { name: 'Welcome! How has your visit been so far?' }).click();
  for (const check of await page.getByRole('checkbox').all()) await check.check();
  await page.getByRole('button', { name: 'Hoàn thành lượt luyện' }).click();
  await page.getByRole('link', { name: 'Xem tiến độ kỹ năng' }).click();
  await expect(page.getByText(/đạt mức “cần gợi ý”.*đạt mức “tự vận dụng”/)).toBeVisible();
  expect(await page.evaluate(() => (window as unknown as { __csp: string[] }).__csp)).toEqual([]);
});
