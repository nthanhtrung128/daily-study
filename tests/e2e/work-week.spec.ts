import { expect, test } from '@playwright/test';
import { audit, trackErrors } from './helpers/audit';
import { stubMedia } from './helpers/stubs';

test('chọn đề từ Hôm nay, giữ memo và ghi âm, trở lại với câu mới khi ngoại tuyến', async ({ page, context }) => {
  const errors = trackErrors(page);
  await page.clock.setFixedTime(new Date('2026-11-24T12:00:00'));
  await page.addInitScript(stubMedia);
  await page.goto('/#hom-nay');
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true);
  const home = page.getByRole('region', { name: 'Tình huống trong tuần' });
  await home.getByText('Chọn tình huống tuần này').click();
  await home.getByRole('button', { name: 'Giải thích thưởng cho nhân viên' }).click();
  const begin = home.getByRole('link', { name: 'Luyện một câu · 2 phút' });
  await begin.click();
  await expect(page.getByRole('heading', { name: 'Giải thích thưởng cho nhân viên' })).toBeFocused();
  await page.getByText('Viết câu trả lời hoặc memo').click();
  const memo = page.getByRole('textbox', { name: 'Memo của lượt này' });
  await memo.fill('Cần ghi nhận nỗ lực cá nhân trước.');
  await expect(page.getByText('Đã lưu trên máy.')).toBeVisible();
  await page.reload();
  await page.getByText('Viết câu trả lời hoặc memo').click();
  await expect(memo).toHaveValue('Cần ghi nhận nỗ lực cá nhân trước.');
  await page.getByRole('button', { name: 'Mở ghi âm (tùy chọn)' }).click();
  await page.getByRole('button', { name: 'Bắt đầu ghi âm' }).click();
  await expect(page.getByRole('button', { name: 'Tôi đã tự trả lời' })).toBeDisabled();
  await page.getByRole('button', { name: 'Dừng & lưu' }).click();
  await expect(page.getByTestId('rec-status')).toContainText('Đã lưu');
  await page.getByRole('button', { name: 'Tôi đã tự trả lời' }).click();
  await expect(page.getByRole('heading', { name: 'Đã lưu lượt luyện' })).toBeFocused();
  await page.getByRole('link', { name: 'Xong · Về Hôm nay' }).click();
  await begin.click();
  await expect(page.getByText('How did the two results turn into my payment?')).toBeVisible();
  await page.getByRole('button', { name: 'Tôi cần gợi ý' }).click();
  await expect(page.getByText(/The team contributed 63 points/)).toBeVisible();
  await page.clock.setFixedTime(new Date('2026-12-03T12:00:00'));
  await page.getByRole('link', { name: 'Xong · Về Hôm nay' }).click();
  await begin.click();
  await expect(page.getByText(/A different plan gives the team 30%/)).toBeVisible();
  const findings: string[] = [];
  await audit(page, 'một câu tuần mới', findings);
  expect(findings).toEqual([]);
  expect(errors).toEqual([]);
});
